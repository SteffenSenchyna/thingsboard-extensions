#!/usr/bin/env python3
"""The app's logo spinner for the custom CSS (`white-labeling/_spinner.scss`), from
`src/app/components/shared/logo-spinner/logo-spinner.svg` (the `tb-logo-spinner` component's keyframes, worked out):

- `$static`: its still parts as a one-colour mask — the tree, its nodes and the ring's track (the mask's alpha 25%);
- `$frames`: the arc's bounce, keyframe by keyframe, as its two ends' angles (clockwise from the top) — the custom CSS
  draws the arc itself (the ring's band cut to them, a round cap at each end) and animates them on each spinner, so
  every spinner starts its bounce from the beginning as it shows (an SVG image's own animation runs one clock for all
  its uses);
- `$duration`, `$reduced-duration`: a round, and with less motion.

Run it again after the spinner changes:

    python3 white-labeling/make-spinner-mask.py
"""
import math
import re
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "src/app/components/shared/logo-spinner/logo-spinner.svg"
OUT = Path(__file__).resolve().parent / "_spinner.scss"

source = SVG.read_text()

# The arc: the ring's line from the slit's left side clockwise to its right, counted as 100.
ring = re.search(r'class="arc" d="M([\d.]+) ([\d.]+)A([\d.]+) [\d.]+ 0 1 1 ([\d.]+) [\d.]+"', source)
x0, y0, radius, x1 = (float(v) for v in ring.groups())
cx, cy = (x0 + x1) / 2, 100.0
start_angle = math.degrees(math.atan2(x0 - cx, -(y0 - cy))) % 360  # the slit's left side, clockwise from the top
span = 360 - 2 * (start_angle - 180)  # round to the slit's right side
per_unit = span / 100

frames = []
for at, length, offset in re.findall(r"([\d.]+)%\{stroke-dasharray:([\d.]+) 200;stroke-dashoffset:(-?[\d.]+)\}", source):
    a = start_angle + -float(offset) * per_unit
    b = a + float(length) * per_unit
    frames.append(f"({at}%, {a:.2f}deg, {b:.2f}deg)")
assert len(frames) > 10, "no keyframes found"
duration = re.search(r"animation:bounce ([\d.]+s)|animation: bounce ([\d.]+s)", source)
duration = next(g for g in duration.groups() if g)
reduced = re.search(r"prefers-reduced-motion: reduce\) \{ \.arc \{ animation-duration: ([\d.]+s)", source).group(1)

# The still parts: the arc and its animation dropped, every colour black.
still = re.sub(r"<!--.*?-->", "", source, flags=re.S)
still = re.sub(r"<path class=\"arc\"[^>]*/>", "", still)
still = re.sub(r"@keyframes bounce\s*\{.*?\}\s*\}", "", still, flags=re.S)
still = re.sub(r"@media \(prefers-(color-scheme: dark|reduced-motion: reduce)\) \{.*?\}\s*\}", "", still, flags=re.S)
still = re.sub(r"(?<=[}>])\s*\.arc\s*\{[^}]*\}", "", still)  # the arc's own rule (not the rule it shares)
still = re.sub(r"#[0-9a-fA-F]{6}\b", "#000", still)
still = re.sub(r"\s+", " ", still).replace("> <", "><").replace('"', "'").strip()
assert "arc" not in still.replace(".track, .tree, .arc", ""), still[:200]
uri = "data:image/svg+xml," + urllib.parse.quote(still, safe=" :/=;,.()-'")

OUT.write_text(
    "// GENERATED by make-spinner-mask.py from src/app/components/shared/logo-spinner/logo-spinner.svg — don't edit\n"
    "// by hand. The logo spinner's still parts as a one-colour mask, and its arc's bounce as its two ends' angles\n"
    "// (clockwise from the top) a keyframe — the custom CSS draws the arc between them.\n\n"
    f'$static: url("{uri}");\n'
    f"$ring-radius: {radius / 2:.4g}%; // of the box (the ring's line), its band the stroke's width\n"
    f"$frames: (\n  " + ",\n  ".join(frames) + "\n);\n"
    f"$duration: {duration};\n"
    f"$reduced-duration: {reduced};\n"
)
print(f"{len(frames)} keyframes, still mask {len(uri)} characters, slit at {start_angle:.2f}° → {OUT.relative_to(ROOT)}")
